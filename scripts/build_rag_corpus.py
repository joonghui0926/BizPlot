def fetch_smba_announcements() -> list[dict]:
    """중소벤처기업부 사업공고 API 조회"""
    docs = []
    try:
        # 중기부 비즈인포 공고 API (XML)
        resp = httpx.get(
            "https://www.bizinfo.go.kr/uss/rss/bizinfoApi.do",
            params={
                "atchFileAt": "N",
                "pnttSeCode": "003",  # 소상공인 지원
                "pageNo": 1,
                "numOfRows": 20,
            },
            timeout=15,
        )
        if resp.status_code == 200:
            import xml.etree.ElementTree as ET
            root = ET.fromstring(resp.text)
            for item in root.findall(".//item"):
                title = getattr(item.find("title"), "text", "") or ""
                desc = getattr(item.find("description"), "text", "") or ""
                link = getattr(item.find("link"), "text", "") or ""
                date_str = getattr(item.find("pubDate"), "text", "") or ""
                if title and desc:
                    docs.append({
                        "source": "smba_announcement",
                        "title": title.strip(),
                        "content": f"{title}\n\n{desc}".strip()[:2000],
                        "url": link,
                    })
    except Exception as e:
        print(f"중기부 공고 API 수집 실패: {e}")

    return docs[:10]


